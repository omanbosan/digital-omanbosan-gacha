# Helper: Unicode-escape any character with ord > 127
# ---------------------------------------------------------------------------
def ue(s):
    result = []
    for ch in s:
        if ord(ch) > 127:
            result.append('\\u{:04x}'.format(ord(ch)))
        else:
            result.append(ch)
    return ''.join(result)


