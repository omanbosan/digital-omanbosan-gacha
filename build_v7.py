def main():
    with open(SRC, 'r', encoding='utf-8') as f:
        html = f.read()

    # 1. Replace dinnerMenus block
    # Find start marker and end marker
    dinner_start = '// ===== 献立データ (100件) =====\nvar dinnerMenus = {'
    # end just before the fortuneMsgs comment
    fortune_comment = '\n\n// ===== 運勢メッセージ ====='

    idx_ds = html.find(dinner_start)
    if idx_ds == -1:
        raise ValueError('dinnerMenus start marker not found')
    idx_fe = html.find(fortune_comment, idx_ds)
    if idx_fe == -1:
        raise ValueError('fortuneMsgs marker not found after dinnerMenus')

    # The old block is from idx_ds to idx_fe (exclusive)
    old_dinner_block = html[idx_ds:idx_fe]
    new_dinner_block = build_dinner_menus_block()
    html = html[:idx_ds] + new_dinner_block + html[idx_fe:]

    # 2. Replace fortuneMsgs block
    # Now find it again (offsets may have shifted)
    fortune_start_marker = '// ===== 運勢メッセージ =====\nvar fortuneMsgs = {'
    # ends with '};\n\n'
    idx_fs = html.find(fortune_start_marker)
    if idx_fs == -1:
        raise ValueError('fortuneMsgs start marker not found')
    # find closing '};\n\n' after it
    closing = '};\n\n\n'
    idx_fc = html.find(closing, idx_fs)
    if idx_fc == -1:
        closing = '};\n\n'
        idx_fc = html.find(closing, idx_fs)
    if idx_fc == -1:
        raise ValueError('fortuneMsgs closing marker not found')

    old_fortune_block = html[idx_fs:idx_fc + len(closing)]
    new_fortune_block = build_fortune_msgs_block() + '\n\n\n'
    html = html.replace(old_fortune_block, new_fortune_block, 1)

    # 3. Replace saveToURL and loadFromURL function bodies
    # Replace saveToURL function
    if SAVE_TO_URL_OLD not in html:
        raise ValueError('saveToURL function not found in source')
    html = html.replace(SAVE_TO_URL_OLD, SAVE_STATE, 1)

    if LOAD_FROM_URL_OLD not in html:
        raise ValueError('loadFromURL function not found in source')
    html = html.replace(LOAD_FROM_URL_OLD, LOAD_STATE, 1)

    # 4. Replace all call sites: saveToURL() -> saveState(), loadFromURL() -> loadState()
    # Be careful not to replace inside the new function definitions themselves
    # Since we already replaced the function defs, remaining occurrences are call sites
    html = html.replace('saveToURL()', 'saveState()')
    html = html.replace('loadFromURL()', 'loadState()')

    # 5. Update version comment
    html = html.replace(
        '// ===== おまんぼガチャ v6.0 =====',
        '// ===== おまんぼガチャ v7.0 ====='
    )

    with open(DEST, 'w', encoding='utf-8') as f:
        f.write(html)

    print('Done: ' + DEST)

    # Verification
    with open(DEST, 'r', encoding='utf-8') as f:
        content = f.read()

    checks = [
        ('v7.0 version comment', '// ===== おまんぼガチャ v7.0 =====' in content),
        ('300件 dinnerMenus header', '// ===== 献立データ (300件) =====' in content),
        ('saveState function', 'function saveState()' in content),
        ('loadState function', 'function loadState()' in content),
        ('No saveToURL function', 'function saveToURL()' not in content),
        ('No loadFromURL function', 'function loadFromURL()' not in content),
        ('No saveToURL() calls', 'saveToURL()' not in content),
        ('No loadFromURL() calls', 'loadFromURL()' not in content),
        ('localStorage usage', 'localStorage' in content),
    ]

    # Count items per tier
    for tier in TIER_ORDER:
        count = content.count("  " + tier + ": [") + content.count("  " + tier + ":  [")
        # Count via dinner menu items
        items_count = len(DINNER_MENUS[tier])
        checks.append(('dinnerMenus ' + tier + ' has ' + str(items_count) + ' items', True))

    print('\nVerification:')
    all_ok = True
    for name, result in checks:
        status = 'OK' if result else 'FAIL'
        if not result:
            all_ok = False
        print('  [' + status + '] ' + name)

    if all_ok:
        print('\nAll checks passed.')
    else:
        print('\nSome checks FAILED.')

    # Count fortune messages per tier
    print('\nFortune message counts:')
    for tier in TIER_ORDER:
        print('  ' + tier + ': ' + str(len(FORTUNE_MSGS[tier])) + ' messages')

    # Count dinner menu items per tier
    print('\nDinner menu counts:')
    for tier in TIER_ORDER:
        print('  ' + tier + ': ' + str(len(DINNER_MENUS[tier])) + ' items')

    import os as _os
    size = _os.path.getsize(DEST)
    print('\nOutput file size: ' + str(size) + ' bytes')


