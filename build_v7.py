SAVE_STATE = """\
function saveState() {
  var today = getTodayStr();
  if (!_mem.usedDate) _mem.usedDate = today;
  try {
    localStorage.setItem('omanbosan_gacha', JSON.stringify({
      points:    _mem.points,
      usedDate:  _mem.usedDate,
      usedToday: _mem.usedToday,
      bonusUsed: _mem.bonusUsed
    }));
  } catch(e) {}
}"""

LOAD_STATE = """\
function loadState() {
  try {
    var raw = localStorage.getItem('omanbosan_gacha');
    if (!raw) return;
    var d = JSON.parse(raw);
    if (d.points   >= 0) _mem.points    = d.points;
    if (d.usedDate)      _mem.usedDate   = d.usedDate;
    if (d.usedToday >= 0) _mem.usedToday = d.usedToday;
    _mem.bonusUsed = d.bonusUsed || false;
    var today = getTodayStr();
    if (_mem.usedDate && _mem.usedDate !== today) {
      _mem.usedToday = 0; _mem.usedDate = today; _mem.bonusUsed = false;
    }
  } catch(e) {}
}"""

