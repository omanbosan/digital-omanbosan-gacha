def build_dinner_menus_block():
    lines = []
    lines.append('// ===== 献立データ (300件) =====')
    lines.append('var dinnerMenus = {')
    for tier in TIER_ORDER:
        items = DINNER_MENUS[tier]
        lines.append('  ' + tier + ': [')
        for name, comment in items:
            n_esc = ue(name)
            c_esc = ue(comment)
            lines.append("    ['" + n_esc + "','" + c_esc + "'],")
        lines.append('  ],')
    lines.append('};')
    return '\n'.join(lines)


