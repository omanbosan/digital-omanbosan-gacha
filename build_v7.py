# Build JS block for fortuneMsgs
# ---------------------------------------------------------------------------
def build_fortune_msgs_block():
    lines = []
    lines.append('// ===== 運勢メッセージ =====')
    lines.append('var fortuneMsgs = {')
    for tier in TIER_ORDER:
        msgs = FORTUNE_MSGS[tier]
        escaped = ["'" + ue(m) + "'" for m in msgs]
        lines.append('  ' + tier + ': [' + ','.join(escaped) + '],')
    lines.append('};')
    return '\n'.join(lines)


